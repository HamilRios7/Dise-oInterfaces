    private void pulsar(JButton boton) {

    
    if (boton.getBackground().equals(Color.BLUE)|| boton.getBackground().equals(Color.RED)) {
        return;
    }

   
    Color colorActual;

    if (turno == 1) {
        colorActual = Color.BLUE;
        boton.setBackground(colorActual);
    } else {
        colorActual = Color.RED;
        boton.setBackground(colorActual);
    }

    jugadas++;

   
    if (comprobarGanador()) {

        if (colorActual.equals(Color.BLUE)) {
            JOptionPane.showMessageDialog(this, "Ha ganado el azul");
        } else {
            JOptionPane.showMessageDialog(this, "Ha ganado el rojo");
        }

        reiniciar();
        return;
    }

    
    if (jugadas == 9) {
        JOptionPane.showMessageDialog(this, "Empate");
        reiniciar();
        return;
    }

    
    if (turno == 1) {
    turno = 2;
    } else {
    turno = 1;
    }
}


private boolean comprobarGanador() {

  
    if (mismaColor(jButtonUno, jButtonDos, jButtonTres)) return true;
    if (mismaColor(jButtonCuatro, jButtonCinco, jButtonSeis)) return true;
    if (mismaColor(jButtonSiete, jButtonOcho, jButtonNuev)) return true;

  
    if (mismaColor(jButtonUno, jButtonCuatro, jButtonSiete)) return true;
    if (mismaColor(jButtonDos, jButtonCinco, jButtonOcho)) return true;
    if (mismaColor(jButtonTres, jButtonSeis, jButtonNuev)) return true;

   
    if (mismaColor(jButtonUno, jButtonCinco, jButtonNuev)) return true;
    if (mismaColor(jButtonTres, jButtonCinco, jButtonSiete)) return true;

    return false;
}

private boolean mismaColor(JButton a, JButton b, JButton c) {
    Color color = a.getBackground();

    return color.equals(b.getBackground()) && color.equals(c.getBackground())&& (color.equals(Color.BLUE) || color.equals(Color.RED));
}

private void reiniciar() {
    jButtonUno.setBackground(null);
    jButtonDos.setBackground(null);
    jButtonTres.setBackground(null);
    jButtonCuatro.setBackground(null);
    jButtonCinco.setBackground(null);
    jButtonSeis.setBackground(null);
    jButtonSiete.setBackground(null);
    jButtonOcho.setBackground(null);
    jButtonNuev.setBackground(null);
    turno = 1;
    jugadas = 0;
}
