     private void eventoNumero(String digito) {//metodo que usan los botones de numero para trabajar las cosas mas faciles
        String actual = jLabelCalculadora.getText();
        if (nuevoNumero || actual.equals("0") || actual.equals("Error")) {//esto sirve para luego de darle al operador  reiniciar el contenido
            jLabelCalculadora.setText(digito);
            nuevoNumero = false;
        } else {
            jLabelCalculadora.setText(actual + digito);
        }
    }
 
      
    private void eventoDecimal() {
        String actual = jLabelCalculadora.getText();
 
        if (nuevoNumero || actual.equals("Error") || actual.equals("")) {//colocaremos automaticamente un 0. si le da al punto decimal
            jLabelCalculadora.setText("0.");
            nuevoNumero = false;
        } else if (!actual.contains(".")) {//aseguramos que no ponga mas de un .
            jLabelCalculadora.setText(actual + ".");
        }
    }
    
    //metodo para cuando das a algun operando
     private void eventosOperaciones(String op) {
         
         //en caso de que este vacio el label al dar a un operando, entonces mostraremos error 
        if (jLabelCalculadora.getText().equals("") || jLabelCalculadora.getText().equals("Error")) {
            jLabelCalculadora.setText("Error");
            return;
        }
      
 
        if (operador != null && !nuevoNumero) { //en caso de haber escrito 2+3 y poner otro operador , hacemos el resultado del primero y continuas con el calculo
            resultado();
            if (jLabelCalculadora.getText().equals("Error")) {//esto solo ocurre cuando se divide entre cero
                return;
            }
        } else {
            numero1 = Double.parseDouble(jLabelCalculadora.getText()); //guardamos el numero de  jlabel primero pasandolo a double y luego lo metemos dentro de variable
        }
 
        operador = op;//guardamos la variable del operador en memoria
        nuevoNumero = true;//hacemos que empieces otro numero nuevo
    }
 
     
     private void resultado() {
        if (operador == null || nuevoNumero) {//comprobamos que operador tenga algo y en nuevoNumero este vacio para que no haga nada si es el caso
            return;
        }
 
        double operando2 = Double.parseDouble(jLabelCalculadora.getText());//pillamos el segundo digito
        double res = 0;//creamos un variable de resultado
 
        switch (operador) {//hacemos un switch para no trabajar con ifs ya que es mas limpio de leer
            case "+":
                res = numero1 + operando2;
                break;
            case "-":
                res = numero1 - operando2;
                break;
            case "*":
                res = numero1 * operando2;
                break;
            case "/":
                if (operando2 == 0) {
                    jLabelCalculadora.setText("Error");
                    operador = null;
                    numero1 = 0;
                    return;
                }
                res = numero1 / operando2;
                break;
        }
 
        jLabelCalculadora.setText(String.valueOf(res));
 
        numero1 = res;//colocamos esto por si quiere seguir calculando con el numero que sale
        operador = null;//colocamos el operador a null
        nuevoNumero = true;//si teclea  se reinicia , sino puede continuar con lo que quiera
    }
 
    private void limpiar() {//esto nos sirve para reiniciar lo de c
        jLabelCalculadora.setText("");//lo colocamos vacio
        //reiniciamos todo
        numero1 = 0; 
        operador = null;
        
    }
    
    
@Override
public void keyTyped(java.awt.event.KeyEvent e) {//usamos keyType para pillar caracteres , con keyPressed , nos pillaria los comandos de Shift para poner operadores
    char tecla = e.getKeyChar();//pillamos lo que tecleemos con char ya que keyType solo devuelve char  y no puedes hacerlo de Strings

    if (tecla >= '0' && tecla <= '9') {
         System.out.println("tecla: " + e.getKeyChar());
        eventoNumero(String.valueOf(tecla));//hacemos que lo pille los numeros por teclado 
    } else if (tecla == '.' || tecla == ',') {
        eventoDecimal(); //que pille para estos dos casos
    } else if (tecla == '+' || tecla == '-' || tecla == '*' || tecla == '/') {
        eventosOperaciones(String.valueOf(tecla));
    } else if (tecla == '=' || tecla == '\n') {
        resultado();//aqui nos dara el resultado si hacemos Enter  ademas del =
    } else if (tecla == 'c' || tecla == 'C' ) {
        limpiar();
    }
}

