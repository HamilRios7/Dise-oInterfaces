      public void mostrarListaFactura(Facturas fact){
        modelolista.addElement(fact);
      }
    
      public void darDatosEdicionFactura(Facturas fact){
     
        jTextFieldAsunto.setText(fact.getAsunto());
        Calendar calendario = Calendar.getInstance();
        calendario.setTime(fact.getFecha());

        jSpinnerDay.setValue(calendario.get(Calendar.DAY_OF_MONTH));
        jSpinnerMonth.setValue(calendario.get(Calendar.MONTH)+1);
        jSpinnerAño.setValue(calendario.get(Calendar.YEAR));

        int cantidad=fact.getCantidad();
        String cantidadS=String.valueOf(cantidad);
        jTextFieldCantidad.setText(cantidadS);
        
        jComboBoxTipo.setSelectedItem(fact.getTipo());
        
        Controlador.setEditarDado(true);
        
        }
      
      
    public void actualizarListaFactura(Facturas actualizada,Facturas factVieja){
        
        modelolista.removeElement(factVieja);
        modelolista.addElement(actualizada);   
        Controlador.setEditarDado(false);    
       }
    
    
    public void eliminarListaFactura(Facturas fact){
        modelolista.removeElement(fact);
    }
    
    
